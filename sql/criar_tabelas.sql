-- Execute este script uma vez na conexao Oracle e no schema da aplicacao.
-- Nao ha comandos DROP: executar novamente em tabelas existentes gera erro.
-- Aplique futuras alteracoes com scripts de migracao, preservando os dados.

CREATE TABLE CLIENTES (
    ID_CLIENTE NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(100) NOT NULL,
    CPF VARCHAR2(20) NOT NULL,
    TELEFONE VARCHAR2(30) NOT NULL,
    EMAIL VARCHAR2(254),
    CONSTRAINT PK_CLIENTES PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT UQ_CLIENTES_CPF UNIQUE (CPF)
);

CREATE TABLE VEICULOS (
    ID_VEICULO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    MARCA VARCHAR2(60) NOT NULL,
    MODELO VARCHAR2(100) NOT NULL,
    ANO NUMBER(4) NOT NULL,
    PLACA VARCHAR2(10) NOT NULL,
    VALOR_DIARIA NUMBER(10, 2) NOT NULL,
    CONSTRAINT PK_VEICULOS PRIMARY KEY (ID_VEICULO),
    CONSTRAINT UQ_VEICULOS_PLACA UNIQUE (PLACA),
    CONSTRAINT CK_VEICULOS_ANO CHECK (ANO BETWEEN 1900 AND 2100),
    CONSTRAINT CK_VEICULOS_VALOR CHECK (VALOR_DIARIA > 0)
);

CREATE TABLE LOCACOES (
    ID_LOCACAO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_CLIENTE NUMBER NOT NULL,
    ID_VEICULO NUMBER NOT NULL,
    DATA_INICIO DATE NOT NULL,
    DATA_FIM_PREVISTO DATE NOT NULL,
    VALOR_DIARIA NUMBER(10, 2) NOT NULL,
    ATIVA CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_LOCACOES PRIMARY KEY (ID_LOCACAO),
    CONSTRAINT FK_LOCACOES_CLIENTES FOREIGN KEY (ID_CLIENTE)
        REFERENCES CLIENTES (ID_CLIENTE),
    CONSTRAINT FK_LOCACOES_VEICULOS FOREIGN KEY (ID_VEICULO)
        REFERENCES VEICULOS (ID_VEICULO),
    CONSTRAINT CK_LOCACOES_DATAS CHECK (DATA_FIM_PREVISTO >= DATA_INICIO),
    CONSTRAINT CK_LOCACOES_VALOR CHECK (VALOR_DIARIA > 0),
    CONSTRAINT CK_LOCACOES_ATIVA CHECK (ATIVA IN ('S', 'N'))
);

CREATE INDEX IDX_LOCACOES_CLIENTE ON LOCACOES (ID_CLIENTE);
CREATE INDEX IDX_LOCACOES_VEICULO ON LOCACOES (ID_VEICULO);
CREATE INDEX IDX_LOCACOES_FIM ON LOCACOES (DATA_FIM_PREVISTO);

-- Impede mais de uma locacao ativa para o mesmo veiculo.
CREATE UNIQUE INDEX UQ_LOCACOES_VEICULO_ATIVO
    ON LOCACOES (CASE WHEN ATIVA = 'S' THEN ID_VEICULO END);
